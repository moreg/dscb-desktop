/**
 * 续写模式覆盖声明。
 *
 * 上面那些守则是按「从零写整章」写的：衔接检查通篇讲「本章开头」、旧版自定义输出要求
 * 可能仍把目标字数定成硬性下限、章末硬性原则要求每次输出都以对话/事件收束。续写时这三条都不成立
 * （开头已写好、字数只是本次增量、章可能还没到收尾的时候），而它们又允许被用户在设置里
 * 覆盖，逐条改内置文本既盖不全也会破坏用户自定义。
 *
 * 所以改成在 system prompt 末尾追加一节显式覆盖声明：位置最靠后、措辞最具体，
 * 与前文冲突时以它为准。
 */
export function buildContinueModeRules(mode: 'extend' | 'finish'): string {
  const lines: string[] = []
  lines.push('【续写模式（本次生效 · 与上文守则冲突时一律以本节为准）】')
  lines.push('')
  lines.push(
    '本次**不是**从零写整章：本章的开头与前部已经写好了（见下文【本章已写正文前部】）。你的任务是**只输出接在前部之后的新正文**，一个字都不要重写前部。'
  )
  lines.push('')
  lines.push('因此上文守则按下列口径执行：')
  lines.push(
    '- **衔接检查 / "本章开头必须对接上一章"**：开头已经写好，禁止重写、复述或另起一个开头。本次只需让新写的第一句紧接【本章已写正文前部】末尾的时间、地点、人物状态。上一章的悬念与未完成事项，若前部已经回应过就不要再回应一遍。'
  )
  lines.push(
    '- **接缝起手硬性铁律（第一句写法）**：前部末尾若有未完成句子、台词或引号，先从断点续完，保留语法、说话人和语意，不得插入动作或另起一句打断；若末句已经完整，才根据情境接下一句对白、行动、感知或反应。严禁首句复述前文末尾台词，禁止自问自答式重述或把上文末尾台词再说一遍；不要用"闻言/听到这话/深吸一口气/事不宜迟/念及此处"等模板承接词起手，不强制动作起手。'
  )
  lines.push(
    '- **细纲三铁律的"顺序/完整"**：先判断前部各剧情点是已完成、进行中还是未开始；先续完进行中的剧情点，再按顺序写第一个尚未开始的剧情点。已经完成的不得重复，也不得倒回去复述；尚未落实的关键动作与结果不能当作已经发生。'
  )
  lines.push(
    '- **质量高于字数**：上文或自定义规则若仍要求"字数硬性下限 / 宁可写超也不要写不够"，本次一律改为篇幅参考。仅补足有叙事用途的内容，禁止为字数重复堆砌、机械扩写、无效铺陈或凭空新增事件；剩余剧情点已完整落实时可以提前结束，关键剧情尚未落实时不得只因字数已够而省略。'
  )
  if (mode === 'finish') {
    lines.push(
      '- **"目标字数是硬性下限 / 宁可写超也不要写不够"**：本次**不适用**。本章篇幅已接近参考目标，下文给出的字数仅供收尾参考，不能据字数认定剧情完成；为凑字数拉长反而是错。'
    )
    lines.push(
      '- **"章末必须以对话或事件结尾"**：只在本章剧情真正完成时适用。剩余剧情尚需展开时保留自然停点，不得跳点压缩；剧情完整后再以对话或事件收束本章，禁止总结式旁白收尾。'
    )
  } else {
    lines.push(
      '- **目标字数**：下文给出的是**本次要新增**的篇幅参考，不是整章字数；已写前部不计入。优先完整落实剩余剧情点，已完整时允许少于参考字数，不得把字数缺口当作添加填充内容的理由。'
    )
    lines.push(
      '- **"章末必须以对话或事件结尾"**：**仅当**本次把本章细纲剧情点全部写完、真正收束本章时才适用。若剧情点还没写完，本次应自然停在剧情推进中，**不要强行收尾**，也不要为了收尾而跳过没写的剧情点。'
    )
  }
  return lines.join('\n').trim()
}

